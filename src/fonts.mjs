/**
 * Text measurement using real LVGL Montserrat font metrics.
 *
 * Metrics come from src/font-metrics.json, generated from LVGL v9.4.0 font
 * sources by scripts/gen-font-metrics.mjs (advance widths per ASCII glyph in
 * px, plus line height, per font size).
 */
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const metrics = JSON.parse(
  readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'font-metrics.json'), 'utf8')
);

export const FONT_SIZES = Object.keys(metrics).map(Number).sort((a, b) => a - b);

/** Font name as registered in the render harness / user firmware. */
export const fontName = (size) => `montserrat_${size}`;

/**
 * Largest available size that does not exceed the CSS px size. Montserrat
 * runs wider than default browser fonts, so rounding down beats clipping.
 */
export function nearestSize(cssPx) {
  return FONT_SIZES.filter((s) => s <= cssPx).pop() ?? FONT_SIZES[0];
}

/** Measured width in px of `text` rendered in montserrat_<size>. */
export function measure(size, text) {
  const { adv } = metrics[size];
  let w = 0;
  for (const ch of text) {
    const code = ch.codePointAt(0);
    // Non-ASCII falls back to the average advance width
    w += code >= 32 && code <= 126 ? adv[code - 32] : avg(size);
  }
  return Math.ceil(w);
}

export const lineHeight = (size) => metrics[size].lineHeight;

/* ------------------------------------------------------------- registries */

/**
 * A font registry answers "which LVGL font renders this element's text, and
 * how wide is that text?" The converter only talks to this interface, so
 * built-in Montserrat and lv_font_conv output are interchangeable.
 */

/** Built-in Montserrat: CSS size rounds down to an available size. */
export function builtinFonts() {
  const at = (size) => ({
    name: fontName(size),
    size,
    measure: (text) => measure(size, text),
    // Montserrat runs wider than typical web fonts, so a too-long string can
    // often be made to fit by dropping one step.
    stepDown: () => {
      const i = FONT_SIZES.indexOf(size) - 1;
      return i >= 0 ? at(FONT_SIZES[i]) : null;
    },
  });
  return { for: (styles) => at(nearestSize(styles.fontSize)), builtinOnly: true };
}

/**
 * Fonts generated by lv_font_conv, falling back to Montserrat for any
 * typeface that could not be resolved to a file.
 */
export function customFonts(built) {
  const byKey = new Map(built.map((f) => [f.key, f]));
  const fallback = builtinFonts();

  return {
    builtinOnly: false,
    fonts: built,
    for(styles) {
      const key = `${slugFamily(styles.fontFamily)}_${styles.fontWeight}${styles.fontItalic ? 'i' : ''}_${styles.fontSize}`;
      const f = byKey.get(key);
      if (!f) return fallback.for(styles);
      const avg = average(f.adv);
      return {
        name: f.key,
        size: f.size,
        measure: (text) => {
          let w = 0;
          for (const ch of text) w += f.adv[ch.codePointAt(0)] ?? avg;
          return Math.ceil(w);
        },
        // The generated font is already the exact CSS size; there is no
        // smaller variant to fall back to.
        stepDown: () => null,
      };
    },
  };
}

const slugFamily = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');

function average(adv) {
  const values = Object.values(adv);
  return values.length ? values.reduce((a, b) => a + b, 0) / values.length : 8;
}

const avgCache = {};
function avg(size) {
  if (!(size in avgCache)) {
    const { adv } = metrics[size];
    avgCache[size] = adv.reduce((a, b) => a + b, 0) / adv.length;
  }
  return avgCache[size];
}
